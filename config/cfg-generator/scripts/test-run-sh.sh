#!/usr/bin/env bash
#
# Integration test: the real run.sh must call cfg-generator before starting
# any NF, and must not start any NF when generation fails.
#
# Each case runs run.sh in a fresh sandbox (a copy of run.sh and config/*.yaml)
# where NF binaries, sudo and mongosh are stubs. A stub NF records its name,
# its -c path and the first line of that file at the moment it starts.
#
# Usage: config/cfg-generator/scripts/test-run-sh.sh   (Linux only)

set -u

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
GEN_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"
REPO_ROOT="$(cd "${GEN_DIR}/../.." && pwd)"
WORK="$(mktemp -d)"
trap 'rm -rf "${WORK}"' EXIT

MARKER="# Code generated by cfg-generator. DO NOT EDIT."
NFS="upf nrf amf smf udr pcf udm nssf ausf chf nef scp bsf n3iwf tngf"
PASS=0
FAIL=0

pass() { PASS=$((PASS + 1)); echo "  ok   $1"; }
fail() { FAIL=$((FAIL + 1)); echo "  FAIL $1"; }
check() { # check <description> <command...>
    local desc=$1
    shift
    if "$@"; then pass "${desc}"; else fail "${desc}"; fi
}

echo "Building cfg-generator..."
(cd "${GEN_DIR}" && CGO_ENABLED=0 go build -o "${WORK}/cfg-generator" .) || {
    echo "build failed"
    exit 1
}

# Stub commands shared by all sandboxes.
STUBS="${WORK}/stubs"
mkdir -p "${STUBS}"
cat > "${STUBS}/sudo" <<'EOF'
#!/usr/bin/env bash
[ "${1:-}" = "-v" ] && exit 0
[ "${1:-}" = "-E" ] && shift
exec "$@"
EOF
printf '#!/usr/bin/env bash\nexit 0\n' > "${STUBS}/mongosh"
cat > "${STUBS}/nf" <<'EOF'
#!/usr/bin/env bash
name=$(basename "$0")
cfg=""
while [ $# -gt 0 ]; do
    case $1 in -c) cfg=$2; shift ;; esac
    shift
done
first=$(head -n 1 "${cfg}" 2>/dev/null)
echo "${name}|${cfg}|${first}" >> "${STUB_LOG}"
EOF
chmod +x "${STUBS}/sudo" "${STUBS}/mongosh" "${STUBS}/nf"

# new_sandbox <name>: prints the sandbox path.
new_sandbox() {
    local box="${WORK}/$1"
    mkdir -p "${box}/bin" "${box}/config"
    cp "${REPO_ROOT}/run.sh" "${box}/"
    cp "${REPO_ROOT}"/config/*.yaml "${box}/config/"
    cp "${WORK}/cfg-generator" "${box}/bin/"
    for nf in ${NFS}; do cp "${STUBS}/nf" "${box}/bin/${nf}"; done
    echo "${box}"
}

# run_sh <sandbox> [env assignments...]: runs run.sh, sets RC and STUB_LOG.
run_sh() {
    local box=$1
    shift
    STUB_LOG="${box}/stub.log"
    : > "${STUB_LOG}"
    (cd "${box}" && env PATH="${STUBS}:${PATH}" STUB_LOG="${STUB_LOG}" "$@" \
        timeout 60 bash ./run.sh > "${box}/run.out" 2>&1)
    RC=$?
}

started() { grep -c . "${STUB_LOG}"; }
count() { ls "$1"/$2 2>/dev/null | wc -l; }

echo "Case 1: first run generates configs, backs up hand-written ones, then starts NFs"
BOX=$(new_sandbox first)
sed -i 's/mcc: "208" # Mobile Country Code/mcc: "001" # Mobile Country Code/' "${BOX}/config/global-config.yaml"
WEBUI_BEFORE=$(sha256sum < "${BOX}/config/webuicfg.yaml")
UEROUTING_BEFORE=$(sha256sum < "${BOX}/config/uerouting.yaml")
run_sh "${BOX}"
check "exit code 0 (got ${RC})" [ "${RC}" -eq 0 ]
check "upf started first" [ "$(head -n 1 "${STUB_LOG}" | cut -d'|' -f1)" = "upf" ]
# Every NF started by default must have read a generated config.
for nf in upf nrf amf smf udr pcf udm nssf ausf chf nef; do
    check "${nf} read a generated config" grep -qxF "${nf}|./config/${nf}cfg.yaml|${MARKER}" "${STUB_LOG}"
done
check "global plmn applied to amfcfg.yaml" grep -q 'mcc: "001"' "${BOX}/config/amfcfg.yaml"
check "global plmn applied to nrfcfg.yaml" grep -q 'mcc: "001"' "${BOX}/config/nrfcfg.yaml"
check "global plmn applied to n3iwfcfg.yaml (not started, still generated)" grep -q 'mcc: "001"' "${BOX}/config/n3iwfcfg.yaml"
check "15 hand-written configs backed up" [ "$(count "${BOX}/config" '*cfg-*.bak.yaml')" -eq 15 ]
check "webuicfg.yaml (unsupported) untouched" [ "$(sha256sum < "${BOX}/config/webuicfg.yaml")" = "${WEBUI_BEFORE}" ]
check "uerouting.yaml (out of scope) untouched" [ "$(sha256sum < "${BOX}/config/uerouting.yaml")" = "${UEROUTING_BEFORE}" ]
check "10 default NFs + upf started" [ "$(started)" -eq 11 ]
check "generator output shown" grep -q 'change(s), 1 not applied, wrote \[upfcfg.yaml nrfcfg.yaml amfcfg.yaml' "${BOX}/run.out"
check "BSF hard-coded PLMN reported as not applied" \
    grep -qF '[not applied] bsf: NRF registration PLMN stays 208/93 (hard-coded); global 001/93 not applied' "${BOX}/run.out"

echo "Case 2: rerun overwrites generated configs without new backups"
sleep 1 # a new backup would get a different timestamp
run_sh "${BOX}"
check "exit code 0 (got ${RC})" [ "${RC}" -eq 0 ]
check "still 15 backups" [ "$(count "${BOX}/config" '*cfg-*.bak.yaml')" -eq 15 ]
check "NFs started again" [ "$(started)" -eq 11 ]

echo "Case 3: invalid global stops run.sh before any NF (exit 2)"
BOX=$(new_sandbox invalid)
sed -i 's/mcc: "208" # Mobile Country Code/mcc: "1" # Mobile Country Code/' "${BOX}/config/global-config.yaml"
AMF_BEFORE=$(sha256sum < "${BOX}/config/amfcfg.yaml")
run_sh "${BOX}"
check "exit code 2 (got ${RC})" [ "${RC}" -eq 2 ]
check "no NF started" [ "$(started)" -eq 0 ]
check "amfcfg.yaml untouched" [ "$(sha256sum < "${BOX}/config/amfcfg.yaml")" = "${AMF_BEFORE}" ]
check "no backup created" [ "$(count "${BOX}/config" '*.bak.yaml')" -eq 0 ]
check "error explains the field" grep -q 'global.plmn.mcc' "${BOX}/run.out"
check "run.pid removed" [ ! -e "${BOX}/run.pid" ]

echo "Case 4: value-mapping mismatch stops run.sh (exit 3)"
BOX=$(new_sandbox mismatch)
sed -i 's/^    - internet$/    - internet\n    - ims/' "${BOX}/config/global-config.yaml"
run_sh "${BOX}"
check "exit code 3 (got ${RC})" [ "${RC}" -eq 3 ]
check "no NF started" [ "$(started)" -eq 0 ]

echo "Case 5: missing generator binary (exit 1)"
BOX=$(new_sandbox nobinary)
rm "${BOX}/bin/cfg-generator"
run_sh "${BOX}"
check "exit code 1 (got ${RC})" [ "${RC}" -eq 1 ]
check "no NF started" [ "$(started)" -eq 0 ]
check "hint to build it" grep -q 'make cfg-generator' "${BOX}/run.out"

echo "Case 6: missing global config (exit 1)"
BOX=$(new_sandbox noinput)
rm "${BOX}/config/global-config.yaml"
run_sh "${BOX}"
check "exit code 1 (got ${RC})" [ "${RC}" -eq 1 ]
check "no NF started" [ "$(started)" -eq 0 ]

echo "Case 7: GLOBAL_CONFIG overrides the input file"
BOX=$(new_sandbox override)
sed 's/mnc: "93" # Mobile Network Code/mnc: "01" # Mobile Network Code/' \
    "${BOX}/config/global-config.yaml" > "${BOX}/alt.yaml"
run_sh "${BOX}" GLOBAL_CONFIG=./alt.yaml
check "exit code 0 (got ${RC})" [ "${RC}" -eq 0 ]
check "alt input applied" grep -q 'mnc: "01"' "${BOX}/config/amfcfg.yaml"

echo "Case 8: quick-setup.sh substitute_ip edits global-config.yaml; run.sh still generates"
BOX=$(new_sandbox quicksetup)
# The exact sed lines quick-setup.sh runs on the global config.
grep -E '^[[:space:]]+sed -i .*config/global-config\.yaml' "${REPO_ROOT}/quick-setup.sh" > "${BOX}/subst.sh"
check "quick-setup edits global-config.yaml 4 times" [ "$(grep -c . "${BOX}/subst.sh")" -eq 4 ]
check "quick-setup no longer edits generated configs" \
    [ "$(grep -cE 'sed -i .*config/(amf|smf|upf)cfg\.yaml' "${REPO_ROOT}/quick-setup.sh")" -eq 0 ]
(cd "${BOX}" && IP_ADDRESS=10.1.2.3 NETWORK_INTERFACE=eth9 bash subst.sh)
run_sh "${BOX}"
check "exit code 0 (got ${RC})" [ "${RC}" -eq 0 ]
check "amf ngapIpList uses the new IP" grep -qA1 '^  ngapIpList:' "${BOX}/config/amfcfg.yaml"
check "amf ngapIpList is 10.1.2.3" [ "$(grep -A1 '^  ngapIpList:' "${BOX}/config/amfcfg.yaml" | tail -n 1 | tr -d ' ')" = "-10.1.2.3" ]
check "smf N3 endpoint is 10.1.2.3" grep -qA1 'endpoints:' "${BOX}/config/smfcfg.yaml"
check "smf endpoint value" [ "$(grep -A1 'endpoints:' "${BOX}/config/smfcfg.yaml" | tail -n 1 | tr -d ' ')" = "-10.1.2.3" ]
check "upf ifList addr is 10.1.2.3" grep -q 'addr: 10.1.2.3' "${BOX}/config/upfcfg.yaml"
check "upf natifname set on both DNNs" [ "$(grep -c 'natifname: eth9' "${BOX}/config/upfcfg.yaml")" -eq 2 ]

# config_digest <sandbox>: one digest over every file name and content in config/.
config_digest() { (cd "$1/config" && ls -A | sort && cat -- *) | sha256sum; }

echo "Case 9: GLOBAL_CONFIG_STRICT=1 with a value BSF cannot apply stops run.sh (exit 6)"
BOX=$(new_sandbox strict)
sed -i 's/mcc: "208" # Mobile Country Code/mcc: "001" # Mobile Country Code/' "${BOX}/config/global-config.yaml"
CONFIG_BEFORE=$(config_digest "${BOX}")
run_sh "${BOX}" GLOBAL_CONFIG_STRICT=1
check "exit code 6 (got ${RC})" [ "${RC}" -eq 6 ]
check "no NF started" [ "$(started)" -eq 0 ]
check "config/ untouched (no file changed, no backup)" [ "$(config_digest "${BOX}")" = "${CONFIG_BEFORE}" ]
check "not-applied item shown" grep -qF '[not applied] bsf: NRF registration PLMN stays 208/93' "${BOX}/run.out"
check "strict error shown" grep -qF '[strict] 1 global value(s) not applied' "${BOX}/run.out"
check "run.sh reports exit code 6" grep -qF 'Config generation failed (exit code 6)' "${BOX}/run.out"
check "run.pid removed" [ ! -e "${BOX}/run.pid" ]

echo "Case 10: same input without GLOBAL_CONFIG_STRICT still starts NFs"
run_sh "${BOX}" GLOBAL_CONFIG_STRICT=0
check "exit code 0 (got ${RC})" [ "${RC}" -eq 0 ]
check "10 default NFs + upf started" [ "$(started)" -eq 11 ]
check "not-applied item still shown" grep -qF '[not applied] bsf:' "${BOX}/run.out"

echo "Case 11: GLOBAL_CONFIG_STRICT=1 with every value applied starts NFs"
BOX=$(new_sandbox strictok)
run_sh "${BOX}" GLOBAL_CONFIG_STRICT=1
check "exit code 0 (got ${RC})" [ "${RC}" -eq 0 ]
check "10 default NFs + upf started" [ "$(started)" -eq 11 ]
check "summary reports 0 not applied" grep -q 'change(s), 0 not applied, wrote' "${BOX}/run.out"

echo
echo "passed: ${PASS}, failed: ${FAIL}"
[ "${FAIL}" -eq 0 ]
